// Liste fermée : le modèle ne peut choisir qu'une de ces icônes.
export const NOMS_ICONES = Object.keys(ICONES);

// Couleurs par thème. Le trait est blanc sur fond sombre et bleu nuit sur
// fond clair ; l'accent jaune est plus soutenu sur fond clair pour rester
// lisible. Jamais de rouge ni de vert (réservés au score).
export const COULEURS_ICONES = {
  sombre: { W: "#ffffff", J: "#ffd23f", V: "#a78bfa" },
  clair: { W: "#1b1f4a", J: "#e0a100", V: "#7c3aed" },
};

// Grille → SVG (chaîne). Un <rect> par suite horizontale de pixels de même
// couleur, sans anticrénelage (crispEdges) pour garder l'effet pixel.
export function svgIcone(nom, { theme = "sombre", taille = 128 } = {}) {
  const grille = ICONES[nom];
  if (!grille) throw new Error(`Icône inconnue : ${nom}`);
  const couleurs = COULEURS_ICONES[theme] ?? COULEURS_ICONES.sombre;
  const rects = [];
  grille.forEach((ligne, y) => {
    let x = 0;
    while (x < ligne.length) {
      const c = ligne[x];
      if (c === ".") {
        x += 1;
        continue;
      }
      let fin = x + 1;
      while (fin < ligne.length && ligne[fin] === c) fin += 1;
      rects.push(`<rect x="${x}" y="${y}" width="${fin - x}" height="1" fill="${couleurs[c]}"/>`);
      x = fin;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${taille}" height="${taille}" viewBox="0 0 ${TAILLE_GRILLE} ${TAILLE_GRILLE}" shape-rendering="crispEdges">${rects.join("")}</svg>`;
}

// SVG en data URI, pour <img src> (page) et next/og (route des images).
export function dataUriIcone(nom, options) {
  return `data:image/svg+xml;base64,${Buffer.from(svgIcone(nom, options)).toString("base64")}`;
}
